//! Static terrain, road, and climate rules catalog.

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct TerrainYields {
    pub(crate) base: [i32; 3],
    pub(crate) road_percent: [i32; 3],
    pub(crate) irrigation: i32,
    pub(crate) mining: i32,
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct RoadYields {
    pub(crate) increment: [i32; 3],
    pub(crate) constant: [i32; 3],
    pub(crate) bonus: [i32; 3],
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub(crate) struct TerrainSpec {
    pub(crate) rule_name: &'static str,
    pub(crate) oceanic: bool,
    pub(crate) movement_cost: i32,
    pub(crate) defense_bonus: i32,
    pub(crate) yields: TerrainYields,
    pub(crate) base_time: i32,
    pub(crate) road_time: i32,
    pub(crate) irrigation_time: i32,
    pub(crate) mining_time: i32,
    pub(crate) cultivate_time: i32,
    pub(crate) plant_time: i32,
    pub(crate) transform_time: i32,
    pub(crate) cultivate_result: Option<&'static str>,
    pub(crate) plant_result: Option<&'static str>,
    pub(crate) transform_result: Option<&'static str>,
    pub(crate) warmer_wetter_result: Option<&'static str>,
    pub(crate) warmer_drier_result: Option<&'static str>,
    pub(crate) cooler_wetter_result: Option<&'static str>,
    pub(crate) cooler_drier_result: Option<&'static str>,
    pub(crate) native_to: &'static [&'static str],
    pub(crate) flags: &'static [&'static str],
}

impl TerrainSpec {
    pub(crate) fn has_flag(&self, flag: &str) -> bool {
        self.flags
            .iter()
            .any(|entry| entry.eq_ignore_ascii_case(flag))
    }

    pub(crate) fn class_name(&self) -> &'static str {
        if self.oceanic { "Oceanic" } else { "Land" }
    }

    pub(crate) fn pillage_time(&self) -> i32 {
        if self.rule_name == "Inaccessible" {
            0
        } else {
            1
        }
    }

    pub(crate) fn extra_removal_time(&self, extra_rule_name: &str) -> i32 {
        if self.rule_name != "Inaccessible"
            && (extra_rule_name.eq_ignore_ascii_case("Pollution")
                || extra_rule_name.eq_ignore_ascii_case("Fallout"))
        {
            3
        } else {
            0
        }
    }
}

