pub(crate) fn terrain_spec(rule_name: &str) -> Option<&'static TerrainSpec> {
    TERRAIN_SPECS
        .iter()
        .find(|spec| spec.rule_name.eq_ignore_ascii_case(rule_name))
}

pub(crate) fn road_yields(name: &str) -> Option<RoadYields> {
    match name.to_ascii_lowercase().as_str() {
        "road" => Some(RoadYields {
            increment: [0, 0, 1],
            constant: [0, 0, 0],
            bonus: [0, 0, 0],
        }),
        "railroad" => Some(RoadYields {
            increment: [0, 0, 0],
            constant: [0, 0, 0],
            bonus: [0, 50, 0],
        }),
        "river" => Some(RoadYields {
            increment: [0, 0, 0],
            constant: [0, 0, 1],
            bonus: [0, 0, 0],
        }),
        _ => None,
    }
}
