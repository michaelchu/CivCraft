#[test]
fn a_v28_route_only_observation_survives_upgrade_until_the_tile_is_reobserved() {
    let mut game = Simulation::new(crate::test_support::seeded_map());
    game.units.clear();
    game.observed_map = Default::default();
    let observer = 1;
    let (x, y) = (23, 36);
    let index = game.map_wrap.index(x, y);
    game.tiles[index].terrain = Terrain::Ocean;
    game.tiles[index].known_by.set(observer, true);
    let old_map = LegacyAiMap(BTreeMap::from([(
        (observer, index),
        schema::MapObservation {
            route: movement::RouteTile {
                terrain: Terrain::Grassland,
                road: true,
                railroad: false,
                river: false,
                city_owner: Some(HUMAN),
            },
            owner: Some(HUMAN),
            ocean: false,
        },
    )]));
    let old = temporary_save("route-only-v28");
    let mut bytes = V28_HEADER.to_vec();
    bytes.extend(
        codec(MAX_PAYLOAD)
            .serialize(&SavedCampaign::from_game(&game, old_map, ()))
            .unwrap(),
    );
    fs::write(&old, bytes).unwrap();
    let game = Simulation::load_campaign(&old).unwrap();
    fs::remove_file(old).unwrap();
    let new = temporary_save("route-only-v29");
    game.save_campaign(&new).unwrap();
    let mut game = Simulation::load_campaign(&new).unwrap();
    fs::remove_file(new).unwrap();
    let known = game.known_tile_for(observer, x, y).unwrap();
    assert_eq!(known.terrain, Terrain::Grassland);
    assert!(known.road);
    assert_eq!(game.observed_city_owner(observer, x, y), Some(HUMAN));

    game.reveal_map_circle(observer, x, y, 0);
    assert_eq!(
        game.known_tile_for(observer, x, y).unwrap().terrain,
        Terrain::Ocean
    );
    assert_eq!(game.observed_city_owner(observer, x, y), None);
}

#[test]
fn large_explored_campaigns_save_reload_and_advance() {
    for dimension in [256, 512] {
        let wrap = MapWrap::with_dimensions(dimension, dimension).unwrap();
        let mut game = Simulation::new(crate::mapgen::generate_with_wrap(42, wrap));
        for tile in &mut game.tiles {
            tile.seen = true;
            tile.known_by.set(HUMAN, true);
            tile.known_by.set(PLAYER_SLOTS - 1, true);
        }
        game.remember_render_map(&[vec![true; wrap.tile_count()]]);
        let path = temporary_save("large-map");
        game.save_campaign(&path).unwrap();
        drop(game);
        let mut loaded = Simulation::load_campaign(&path).unwrap();
        fs::remove_file(path).unwrap();
        assert_eq!(loaded.map_wrap, wrap);
        assert!(
            loaded.tiles.iter().all(|tile| {
                tile.seen && tile.known_by[HUMAN] && tile.known_by[PLAYER_SLOTS - 1]
            })
        );
        assert!((0..wrap.tile_count()).all(|index| {
            let (x, y) = wrap.position(index);
            loaded.observed_route_tile(x, y).is_some()
        }));
        let turn = loaded.turn;
        loaded.simulate_turn();
        assert_eq!(loaded.turn, turn + 1);
    }
}

